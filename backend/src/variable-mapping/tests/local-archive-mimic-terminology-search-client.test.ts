import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { mkdir, mkdtemp, readFile, readdir, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import test from "node:test";
import { gzip } from "node:zlib";
import { promisify } from "node:util";
import { LocalArchiveMimicTerminologySearchClient } from "../index.js";

const gzipAsync = promisify(gzip);

test("searches only aggregate dictionary metadata in a local MIMIC archive", async (context) => {
  const directory = await mkdtemp(join(tmpdir(), "mimic-dictionary-")); context.after(() => rm(directory, { recursive: true, force: true }));
  const memberDirectory = join(directory, "arbitrary-release-name", "hosp"); await mkdir(memberDirectory, { recursive: true });
  const rows = ["itemid,label,fluid,category", ...Array.from({ length: 20 }, (_, index) => `${100 + index},Lactate ${index},Blood,Lab`), "999,Blood pressure,Other,Lab"].join("\n");
  await writeFile(join(memberDirectory, "d_labitems.csv.gz"), await gzipAsync(`${rows}\n`));
  const icuDirectory = join(directory, "arbitrary-release-name", "icu"); await mkdir(icuDirectory, { recursive: true });
  await writeFile(join(icuDirectory, "d_items.csv.gz"), await gzipAsync("itemid,label,abbreviation,linksto,category,unitname,param_type,lownormalvalue,highnormalvalue\n700,Shared clinical label,Shared,chartevents,Scores,,Text,,\n701,Metoprolol rate,Rate,inputevents,Medications,mg/min,Numeric,,\n"));
  const diagnosisRows = ["icd_code,icd_version,long_title", "A100,10,Shared clinical label", "A101,10,Related diagnosis", ...Array.from({ length: 300 }, (_, index) => `A10${String(index + 2).padStart(3, "0")},10,Prefix diagnosis ${index + 2}`)];
  await writeFile(join(memberDirectory, "d_icd_diagnoses.csv.gz"), await gzipAsync(`${diagnosisRows.join("\n")}\n`));
  await writeFile(join(memberDirectory, "prescriptions.csv.gz"), await gzipAsync("subject_id,hadm_id,starttime,stoptime,drug,dose_val_rx,dose_unit_rx,route\n1,10,2020-01-01,2020-01-02,Metoprolol,25,mg,PO\n2,20,2020-01-01,2020-01-02,Metoprolol,50,mg,PO\n3,30,2020-01-01,2020-01-02,Atenolol,25,mg,PO\n"));
  const archive = join(directory, "mimic.zip"); const zipped = spawnSync("zip", ["-q", "-r", archive, "arbitrary-release-name"], { cwd: directory });
  assert.equal(zipped.status, 0);
  const matches = await new LocalArchiveMimicTerminologySearchClient(archive).search("lactate");
  assert.equal(matches.length, 20); assert.equal(matches[0]?.dictionary, "d_labitems"); assert.equal(matches[0]?.identifier, "100");
  const expandedPhraseMatches = await new LocalArchiveMimicTerminologySearchClient(archive).search("blood lactate level");
  assert.equal(expandedPhraseMatches.length, 20);
  assert.equal(expandedPhraseMatches.some(({ identifier }) => identifier === "999"), false);
  const terminologyCache = join(directory, "terminology-cache");
  const medicationClient = new LocalArchiveMimicTerminologySearchClient(archive, { cacheDirectory: terminologyCache });
  const medications = await medicationClient.search("metoprolol");
  assert.equal(medications.some(({ dictionary }) => dictionary === "prescriptions_drug"), true);
  assert.equal(medications.find(({ dictionary }) => dictionary === "prescriptions_drug")?.source_table, "prescriptions");
  const medicationOnly = await medicationClient.searchMedication("metoprolol");
  assert.deepEqual(medicationOnly.map(({ dictionary }) => dictionary), ["prescriptions_drug"]);
  const medicationCacheFile = (await readdir(terminologyCache)).find((name) => name.startsWith("prescriptions_drug-"));
  assert.ok(medicationCacheFile);
  const medicationCache = await readFile(join(terminologyCache, medicationCacheFile), "utf8");
  assert.doesNotMatch(medicationCache, /subject_id|hadm_id|starttime|dose_val_rx/u);
  const nonMedication = await new LocalArchiveMimicTerminologySearchClient(archive).searchNonMedication("metoprolol");
  assert.equal(nonMedication.some(({ dictionary }) => dictionary === "prescriptions_drug"), false);
  const sharedLabel = await new LocalArchiveMimicTerminologySearchClient(archive).search("shared clinical label");
  assert.deepEqual(new Set(sharedLabel.map(({ dictionary }) => dictionary)), new Set(["d_items", "d_icd_diagnoses"]));
  const diagnosisDomain = await new LocalArchiveMimicTerminologySearchClient(archive).searchByCategory("shared clinical label", "diagnosis");
  assert.deepEqual(diagnosisDomain.map(({ dictionary }) => dictionary), ["d_icd_diagnoses"]);
  const laboratoryDomain = await new LocalArchiveMimicTerminologySearchClient(archive).searchByCategory("shared clinical label", "laboratory");
  assert.deepEqual(laboratoryDomain.map(({ dictionary }) => dictionary), []);
  const codePrefix = await new LocalArchiveMimicTerminologySearchClient(archive).searchCodePrefix("A10");
  assert.equal(codePrefix.length, 302);
  assert.equal(new Set(codePrefix.map(({ identifier }) => identifier)).size, 302);
  assert.equal(codePrefix.every(({ identifier }) => identifier.startsWith("A10")), true);
});
